package seal

import (
	"encoding/base64"
	"encoding/hex"
	"strings"
)

type SealVector struct {
	Name   string `json:"name"`
	Kind   string `json:"kind"`
	ID     string `json:"id"`
	Salt   string `json:"salt"`
	Plain  string `json:"plain"`
	Sealed string `json:"sealed"`
}

type Vectors struct {
	Comment    string            `json:"comment"`
	SyncKey    string            `json:"syncKey"`
	Display    string            `json:"display"`
	AuthToken  string            `json:"authTokenBase64Url"`
	EncKey     string            `json:"encKey"`
	IDKey      string            `json:"idKey"`
	LabelIDs   map[string]string `json:"labelIds"`
	BlobIDs    map[string]string `json:"blobIds"`
	Padme      map[string]uint64 `json:"padme"`
	SealedSize map[string]int    `json:"sealedSize"`
	Seal       []SealVector      `json:"seal"`
}

func hexd(s string) []byte {
	b, err := hex.DecodeString(s)
	if err != nil {
		panic(err)
	}
	return b
}

func pattern(n int, seed byte) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte(i*31) ^ seed
	}
	return b
}

// Generate builds deterministic test vectors. All inputs are fixed.
func Generate() Vectors {
	k := pattern(32, 0x5a)
	keys := DeriveKeys(k)
	v := Vectors{
		Comment:    "All byte strings are lower-case hex. Generated by `go run ./cmd/vectors`. Do not edit.",
		SyncKey:    hex.EncodeToString(k),
		Display:    FormatKey(k),
		AuthToken:  base64.RawURLEncoding.EncodeToString(keys.AuthToken),
		EncKey:     hex.EncodeToString(keys.EncKey),
		IDKey:      hex.EncodeToString(keys.IDKey),
		LabelIDs:   map[string]string{},
		BlobIDs:    map[string]string{},
		Padme:      map[string]uint64{},
		SealedSize: map[string]int{},
	}
	for _, l := range []string{"Work", "Einkäufe", "日本語", ""} {
		v.LabelIDs[l] = LabelID(keys.IDKey, l)
	}
	for _, n := range []string{"0b0e4f6a-1c2d-4e5f-8a9b-0c1d2e3f4a5b.jpg", "rec.m4a"} {
		v.BlobIDs[n] = BlobID(keys.IDKey, n)
	}
	for _, n := range []uint64{8, 255, 256, 257, 1000, 65536, 70000, 1048577} {
		v.Padme[itoa(int(n))] = Padme(n)
	}
	for _, n := range []int{0, 100, 248, 249, 65528, 65529, 200000} {
		v.SealedSize[itoa(n)] = SealedSize(n)
	}
	add := func(name, kind, id string, saltSeed byte, m []byte) {
		salt := pattern(32, saltSeed)
		v.Seal = append(v.Seal, SealVector{
			Name: name, Kind: kind, ID: id,
			Salt:   hex.EncodeToString(salt),
			Plain:  hex.EncodeToString(m),
			Sealed: hex.EncodeToString(Seal(keys.EncKey, salt, AD(kind, id), m)),
		})
	}
	noteID := "0123456789abcdef0123456789abcdef"
	add("empty", "note", noteID, 1, nil)
	add("note json", "note", noteID, 2, []byte(`{"v":1,"type":"NOTE","title":"Hëllo","body":"world"}`))
	add("label", "label", LabelID(keys.IDKey, "Work"), 3, []byte(`{"v":1,"value":"Work","order":0}`))
	add("two chunks", "blob", BlobID(keys.IDKey, "rec.m4a"), 4, pattern(70000, 9))
	add("exact chunk", "blob", BlobID(keys.IDKey, "rec.m4a"), 5, []byte(strings.Repeat("x", 65528)))
	return v
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var b []byte
	for ; n > 0; n /= 10 {
		b = append([]byte{byte('0' + n%10)}, b...)
	}
	return string(b)
}
